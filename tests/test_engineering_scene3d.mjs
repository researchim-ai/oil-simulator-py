import fs from 'node:fs';
import assert from 'node:assert/strict';
import {FieldScene3D} from '../apps/fieldroom/scene3d.js';
globalThis.ResizeObserver=class {observe(){}};
globalThis.requestAnimationFrame=()=>1;
globalThis.devicePixelRatio=1;
globalThis.document={querySelector:()=>null};
const ctx=new Proxy({measureText:t=>({width:t.length*7})},{get:(o,k)=>o[k]??(()=>{})});
const canvas={clientWidth:1000,closest:()=>null,getContext:()=>ctx,addEventListener(){},getBoundingClientRect:()=>({width:1000,height:560})};
let chosen;
const scene=new FieldScene3D(canvas,id=>chosen=id);
const d=JSON.parse(fs.readFileSync(new URL('../apps/fieldroom/data/engineering-case.json', import.meta.url)));
scene.update(d,d.frames.at(-1),'facility');scene.draw();
for(const w of d.topology.wells)assert(scene.hits.some(h=>h.id==='well:'+w.name));
for(const p of d.topology.gathering.pipes)assert(scene.hits.some(h=>h.id==='pipe:'+p.name));
for(const p of scene.items.flatMap(x=>x.points))assert(p.every(Number.isFinite));
const h=scene.hits.find(h=>h.label&&h.id==='well:P1');scene.pick(h.label[0]+3,h.label[1]+3);assert.equal(chosen,'well:P1');
const old=scene.fieldCache;scene.update(d,d.frames[0],'well:P1');scene.draw();assert.equal(scene.fieldCache,old);
scene.field='s_o';scene.draw();assert.equal(scene.fieldCache.values[0],1-d.field.s_w[0]-d.field.s_g[0]);
scene.showField=false;scene.draw();assert(!scene.hits.some(h=>h.id?.startsWith('cell:')));
assert.equal(d.field.time_days,30);
console.log('PASS: finite projections, all wells/pipes, picking, cached final fields, So, hidden reservoir');
